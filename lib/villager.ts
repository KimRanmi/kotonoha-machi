export const DEFAULT_VILLAGER_ID = "cafe";

export function getVillager(id?: string | null): VillagerProfile {
  if (id && VILLAGERS[id]) return VILLAGERS[id];
  return VILLAGERS[DEFAULT_VILLAGER_ID];
}

